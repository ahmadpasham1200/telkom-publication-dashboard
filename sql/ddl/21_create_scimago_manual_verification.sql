-- Append-only audit history for manual SCImago decisions.
-- Apply manually; the Python CLI never executes schema changes.
BEGIN;

CREATE TABLE IF NOT EXISTS raw.scimago_manual_verification (
    manual_verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id BIGINT NOT NULL REFERENCES raw.journal_catalog(journal_id),
    confirmed_title TEXT NOT NULL,
    issn TEXT,
    eissn TEXT,
    decision TEXT NOT NULL,
    sjr NUMERIC,
    quartile TEXT,
    evidence_url TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_scimago_manual_decision
        CHECK (decision IN ('verified', 'unverified', 'not_journal')),
    CONSTRAINT ck_scimago_manual_quartile
        CHECK (quartile IS NULL OR quartile IN ('Q1', 'Q2', 'Q3', 'Q4')),
    CONSTRAINT ck_scimago_manual_sjr_positive
        CHECK (sjr IS NULL OR sjr > 0),
    CONSTRAINT ck_scimago_manual_issn_format
        CHECK (issn IS NULL OR issn ~ '^[0-9]{4}-[0-9]{3}[0-9X]$'),
    CONSTRAINT ck_scimago_manual_eissn_format
        CHECK (eissn IS NULL OR eissn ~ '^[0-9]{4}-[0-9]{3}[0-9X]$')
);

CREATE INDEX IF NOT EXISTS ix_scimago_manual_verification_journal_history
    ON raw.scimago_manual_verification (journal_id, created_at DESC,
                                        manual_verification_id DESC);

-- The current-status projection still uses the existing source/status vocabulary.
-- Manual verified decisions may omit a URL after the CLI warning; the audit row
-- and metadata.verification_type='manual' make that exception explicit.
ALTER TABLE raw.journal_index_verification
    DROP CONSTRAINT IF EXISTS journal_index_verification_verified_check;
ALTER TABLE raw.journal_index_verification
    ADD CONSTRAINT journal_index_verification_verified_check
    CHECK (status <> 'verified' OR
           (indexed IS TRUE AND
            (evidence_url IS NOT NULL OR metadata->>'verification_type' = 'manual')));

COMMIT;
